const copies: Record<Locale, Copy> = { en, fr, es, de, pt } as Record<Locale, Copy>;

export function useSmartPricingCopy(): Copy {
  const { locale } = useLanguage();
  return copies[locale] ?? en;
}

export function ruleSummary(copy: Copy, applied: { rule: string; label?: string; percent?: number }[]): string {
  return applied
    .map((a) => `${a.label ?? copy.rules[a.rule] ?? a.rule}${a.percent !== undefined ? ` ${a.percent > 0 ? "+" : ""}${a.percent}%` : ""}`)
    .join(" · ");
}
